#!/usr/bin/env python3
"""Turn data/cube-certs.txt (lines `N p a`) into Lean certificate modules.

Each certificate is packed as  c = p + 2^61*a + 2^69*i + 2^75*j  (81 bits) with i = v2(p-1),
j = v3(p-1); BLOCK consecutive certificates form one natural-number literal, lowest first, and one
theorem  `blockOK <literal> BLOCK <first N> = true := by decide +kernel`.
Writes GRHCorollaries/Cubes/Certs/S??.lean (FILE_BLOCKS blocks each, Mathlib-free) and
GRHCorollaries/Cubes/Finite.lean (the cover of [1, NMAX]).  Nothing here is trusted: the Lean
kernel re-checks every certificate through `GRHCorollaries.Cubes.certOK`.
"""
import os, sys
BLOCK, FILE_BLOCKS = 1000, 50
root = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
certs = []
for line in open(os.path.join(root, 'data', 'cube-certs.txt')):
    N, p, a = map(int, line.split())
    assert N == len(certs) + 1
    certs.append((p, a))
NMAX = len(certs)
assert NMAX % BLOCK == 0

def val(m, q):
    v = 0
    while m % q == 0: m //= q; v += 1
    return v

def pack(p, a):
    i, j = val(p - 1, 2), val(p - 1, 3)
    assert p < 2**61 and a < 256 and 1 <= i < 64 and 1 <= j < 64
    assert (2**i * 3**j + 1) ** 2 > p
    return p + (a << 61) + (i << 69) + (j << 75)

nblocks = NMAX // BLOCK
nfiles = -(-nblocks // FILE_BLOCKS)
cdir = os.path.join(root, 'GRHCorollaries', 'Cubes', 'Certs')
os.makedirs(cdir, exist_ok=True)
for f in range(nfiles):
    out = [f"""/-
Generated by scripts/gen_cube_shards.py from data/cube-certs.txt. Do not edit.
Blocks {f * FILE_BLOCKS}..{min(nblocks, (f + 1) * FILE_BLOCKS) - 1}: certificates for a prime in (N^3, (N+1)^3),
N = {f * FILE_BLOCKS * BLOCK + 1} .. {min(nblocks, (f + 1) * FILE_BLOCKS) * BLOCK}. Each theorem is checked by the Lean kernel (`decide +kernel`).
-/
import GRHCorollaries.Cubes.Defs

namespace GRHCorollaries.Cubes.Certs
"""]
    for b in range(f * FILE_BLOCKS, min(nblocks, (f + 1) * FILE_BLOCKS)):
        lo = b * BLOCK + 1
        data = 0
        for k in range(BLOCK):
            data |= pack(*certs[lo - 1 + k]) << (81 * k)
        out.append(f"theorem b{b:04d} : blockOK 0x{data:x} {BLOCK} {lo} = true := by decide +kernel\n")
    out.append("\nend GRHCorollaries.Cubes.Certs\n")
    open(os.path.join(cdir, f"S{f:02d}.lean"), 'w').write('\n'.join(out))

# the cover file
L = ["""/-
Generated by scripts/gen_cube_shards.py. Do not edit.

A prime strictly between `N ^ 3` and `(N + 1) ^ 3` for every `1 ≤ N ≤ %d`, with no hypothesis:
each `N` has a kernel-checked Pocklington certificate (modules `GRHCorollaries.Cubes.Certs.S*`),
and `GRHCorollaries.Cubes.exists_prime_of_blockOK` turns accepted blocks into primes.
-/
import GRHCorollaries.Cubes.Soundness
""" % NMAX]
for f in range(nfiles):
    L.append(f"import GRHCorollaries.Cubes.Certs.S{f:02d}")
L.append("""
namespace GRHCorollaries.Cubes

/-- There is a prime strictly between `N ^ 3` and `(N + 1) ^ 3`. -/
abbrev PrimeBetweenCubes (N : ℕ) : Prop := ∃ p : ℕ, p.Prime ∧ N ^ 3 < p ∧ p < (N + 1) ^ 3

private theorem cover {P : ℕ → Prop} {a b c : ℕ} (h1 : ∀ N, a ≤ N → N < b → P N)
    (h2 : ∀ N, b ≤ N → N < c → P N) : ∀ N, a ≤ N → N < c → P N :=
  fun N ha hc => (Nat.lt_or_ge N b).elim (h1 N ha) (fun hb => h2 N hb hc)
""")
for b in range(nblocks):
    lo, hi = b * BLOCK + 1, (b + 1) * BLOCK + 1
    L.append(f"private theorem r{b:04d} : ∀ N, {lo} ≤ N → N < {hi} → PrimeBetweenCubes N :=\n"
             f"  fun N h1 h2 => exists_prime_of_blockOK (by norm_num) Certs.b{b:04d} N h1 (by omega)")
def chain(names):
    return names[0] if len(names) == 1 else f"cover {names[0]} ({chain(names[1:])})"
fnames = []
for f in range(nfiles):
    bs = list(range(f * FILE_BLOCKS, min(nblocks, (f + 1) * FILE_BLOCKS)))
    lo, hi = bs[0] * BLOCK + 1, (bs[-1] + 1) * BLOCK + 1
    L.append(f"\nprivate theorem f{f:02d} : ∀ N, {lo} ≤ N → N < {hi} → PrimeBetweenCubes N :=\n  "
             + chain([f"r{b:04d}" for b in bs]))
    fnames.append(f"f{f:02d}")
L.append(f"""
/-- **Finite range, no hypothesis.** For `1 ≤ N ≤ {NMAX}` there is a prime strictly between
`N ^ 3` and `(N + 1) ^ 3`. -/
theorem exists_prime_between_cubes_of_le : ∀ N, 1 ≤ N → N < {NMAX + 1} → PrimeBetweenCubes N :=
  {chain(fnames)}

end GRHCorollaries.Cubes
""")
open(os.path.join(root, 'GRHCorollaries', 'Cubes', 'Finite.lean'), 'w').write('\n'.join(L))
print(f"{NMAX} certificates, {nblocks} blocks of {BLOCK}, {nfiles} files")
